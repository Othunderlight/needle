#!/usr/bin/env python3
import evdev
from evdev import InputDevice, ecodes
import time
import sys
import select
import os
import glob

# 1. Detect Screen Resolution
def get_screen_resolution():
    for mode_path in glob.glob("/sys/class/drm/*/modes"):
        try:
            with open(mode_path, "r") as f:
                line = f.readline().strip()
                if "x" in line:
                    w, h = map(int, line.split("x"))
                    return w, h
        except Exception:
            pass
    return 1920, 1080

SCREEN_W, SCREEN_H = get_screen_resolution()
print(f"[+] Screen Resolution: {SCREEN_W}x{SCREEN_H}")

# 2. Grab All Input Devices
devices = []
for path in evdev.list_devices():
    try:
        dev = InputDevice(path)
        caps = dev.capabilities()
        if ecodes.EV_KEY in caps or ecodes.EV_REL in caps:
            devices.append(dev)
    except Exception:
        pass

if not devices:
    print("[-] No input devices found. Run with sudo.")
    sys.exit(1)

# 3. Calibration: Slam to (0,0)
print("[+] Calibrating cursor to top-left corner...")
os.system("ydotool mousemove -- -50000 -50000")
time.sleep(0.3)

cur_x = 0
cur_y = 0
last_x = 0
last_y = 0

output_file = "playback.sh"
events_recorded = []
last_time = time.time()

MOUSE_CLICK_MAP = {
    ecodes.BTN_LEFT: "0xC0",
    ecodes.BTN_RIGHT: "0xC1",
    ecodes.BTN_MIDDLE: "0xC2",
}

print(f"[+] Recording started on {len(devices)} device(s)!")
print("[+] Perform your actions. Press Ctrl+C when finished.\n")

try:
    fd_to_dev = {dev.fd: dev for dev in devices}

    while True:
        r, _, _ = select.select(fd_to_dev.keys(), [], [])
        for fd in r:
            dev = fd_to_dev[fd]
            for event in dev.read():
                now = time.time()
                delay = round(now - last_time, 2)

                # Track position
                if event.type == ecodes.EV_REL:
                    if event.code == ecodes.REL_X:
                        cur_x = max(0, min(SCREEN_W, cur_x + event.value))
                    elif event.code == ecodes.REL_Y:
                        cur_y = max(0, min(SCREEN_H, cur_y + event.value))

                    sys.stdout.write(f"\r[Tracking] Cursor: X={cur_x:4d}, Y={cur_y:4d}   ")
                    sys.stdout.flush()

                # Mouse Clicks & Keys
                elif event.type == ecodes.EV_KEY and event.value == 1:

                    # Mouse Click
                    if event.code in MOUSE_CLICK_MAP:
                        btn = MOUSE_CLICK_MAP[event.code]

                        # Calculate the single vector jump from previous location
                        dx = cur_x - last_x
                        dy = cur_y - last_y

                        events_recorded.append(f"sleep {max(delay, 0.05)}")
                        # Move directly to the target button
                        if dx != 0 or dy != 0:
                            events_recorded.append(f"ydotool mousemove -- {dx} {dy}")
                        events_recorded.append(f"ydotool click {btn}")

                        last_x = cur_x
                        last_y = cur_y
                        last_time = now
                        print(f"\n[Recorded Click] Target: ({cur_x}, {cur_y}) | Jump: ({dx}, {dy})")

                    # Keyboard Key
                    elif event.code < 256:
                        events_recorded.append(f"sleep {max(delay, 0.05)}")
                        events_recorded.append(f"ydotool key {event.code}:1 {event.code}:0")
                        last_time = now

except KeyboardInterrupt:
    print("\n\n[+] Stopping recording...")

# Write to playback.sh
with open(output_file, "w") as f:
    f.write("#!/usr/bin/env bash\n")
    f.write("# Automatically generated by recorder.py\n\n")
    f.write("echo 'Starting playback in 2 seconds...'\n")
    f.write("sleep 2\n\n")
    # THE SECRET SAUCE: Slam to top-left corner so start position NEVER matters
    f.write("# Reset cursor to (0,0) baseline\n")
    f.write("ydotool mousemove -- -50000 -50000\n")
    f.write("sleep 0.1\n\n")

    for cmd in events_recorded:
        f.write(f"{cmd}\n")

os.chmod(output_file, 0o755)

print(f"[✔] Successfully saved to '{output_file}'.")
print(f"[✔] Replay anytime with: ./{output_file}")
